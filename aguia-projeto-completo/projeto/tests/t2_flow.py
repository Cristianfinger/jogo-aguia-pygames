import json, sys
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from srv import serve
from playwright.sync_api import sync_playwright
fails = []
def check(cond, msg):
    print(("  ok  " if cond else "  FALHA ") + msg)
    if not cond: fails.append(msg)

def wait_state(pg, st, t=8000):
    pg.wait_for_function(f"Aguia.app.state==='{st}'", timeout=t)

def world(pg, expr): return pg.evaluate(f"(()=>{{const w=Aguia.app.world; return {expr}}})()")

_srv = serve(); URL = _srv.__enter__()
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={"width":1280,"height":800}); pg = ctx.new_page(); errs=[]
    pg.on("console", lambda m: errs.append(m.text) if m.type=="error" else None)
    pg.on("pageerror", lambda e: errs.append("pageerror "+str(e)))
    pg.goto(URL); wait_state(pg, "menu")
    print("# Fluxo no desktop")
    check(pg.locator("#btnContinue").is_hidden(), "sem progresso salvo: botão Continuar escondido")
    pg.click("#btnHow"); check(pg.locator("#sc-how").is_visible(), "tela Como jogar abre"); pg.screenshot(path="/home/claude/s_how.png")
    pg.click("#sc-how [data-back]"); check(pg.locator("#sc-menu").is_visible(), "Entendi volta ao menu")
    pg.click("#btnSound"); check("desligado" in pg.inner_text("#btnSound").lower(), "botão de som alterna"); pg.click("#btnSound")
    pg.click("#btnNew"); wait_state(pg, "play"); pg.wait_for_timeout(1400)
    pg.screenshot(path="/home/claude/s_play1.png")
    check(pg.locator("#hud").is_visible() and "nível 1" in pg.inner_text("#banner").lower(), "HUD e faixa 'Nível 1' aparecem")
    x0 = world(pg, "w.px"); pg.keyboard.down("ArrowLeft"); pg.wait_for_timeout(500); pg.keyboard.up("ArrowLeft"); x1 = world(pg, "w.px")
    check(x1 < x0 - 30, f"seta esquerda move a águia ({x0:.0f} -> {x1:.0f})")
    box = pg.locator("#cv").bounding_box(); cx, cy = box["x"]+box["width"]/2, box["y"]+box["height"]*0.9
    x2 = world(pg, "w.px"); pg.mouse.move(cx, cy); pg.mouse.down(); pg.mouse.move(cx+120, cy, steps=12); pg.wait_for_timeout(450)
    x3 = world(pg, "w.px"); pg.mouse.up()
    check(x3 > x2 + 60, f"arrastar com o mouse move a águia ({x2:.0f} -> {x3:.0f})")
    pg.wait_for_timeout(500); xs = world(pg, "w.px"); pg.wait_for_timeout(300); xe = world(pg, "w.px")
    check(abs(xe - xs) < 6, "ao soltar, a águia para")
    pg.keyboard.press("p"); wait_state(pg, "pause"); pg.wait_for_timeout(250); pg.screenshot(path="/home/claude/s_pause.png")
    sv = pg.evaluate("localStorage.getItem('aguia.save.v1')"); check(sv is not None and json.loads(sv)["level"]==1, "pausar grava o progresso")
    t_a = world(pg, "w.lt"); pg.wait_for_timeout(600); check(abs(world(pg,"w.lt")-t_a) < 0.001, "jogo congela na pausa")
    pg.keyboard.press("p"); wait_state(pg, "play")
    pg.evaluate("(()=>{const w=Aguia.app.world; w.score=1234; w.level=6; w.inv=0; w.hp=1; w.hurt();})()")
    wait_state(pg, "over"); pg.wait_for_timeout(300); pg.screenshot(path="/home/claude/s_over.png")
    check(pg.inner_text("#overScore").replace(".","")=="1234", "tela de fim mostra 1.234 pontos")
    check(pg.evaluate("localStorage.getItem('aguia.save.v1')") is None, "fim de jogo apaga o autosave")
    pg.fill("#nameIn", "Cristian <b>"); pg.click("#btnSave"); pg.wait_for_function("document.getElementById('overMsg').textContent.includes('Nº')", timeout=8000)
    check("Nº 1" in pg.inner_text("#overMsg"), "pontuação salva: " + pg.inner_text("#overMsg"))
    rk = json.loads(pg.evaluate("localStorage.getItem('aguia.rank.v1')")); check(rk[0]["name"]=="Cristian b" and rk[0]["score"]==1234, f"nome higienizado no ranking: {rk[0]['name']!r}")
    pg.click("#btnRank2"); pg.wait_for_timeout(500); pg.screenshot(path="/home/claude/s_rank.png")
    check("Cristian" in pg.inner_text("#rankRows") and pg.locator("#rankRows li.me").count()==1, "ranking lista e destaca a sua pontuação")
    check(pg.locator("#rankTabs").is_hidden(), "sem backend online: abas escondidas")
    pg.click("#sc-rank [data-back]"); check(pg.locator("#sc-over").is_visible(), "Voltar no ranking retorna ao fim de jogo")
    pg.click("#btnMenu2"); wait_state(pg, "menu"); check(pg.locator("#btnContinue").is_hidden(), "após o fim não há 'Continuar'")
    print("# Continuar / Novo jogo")
    pg.click("#btnNew"); wait_state(pg, "play"); pg.wait_for_timeout(1000)
    pg.evaluate("(()=>{const w=Aguia.app.world; w.score=777; w.hp=3;})()")
    pg.keyboard.press("Escape"); wait_state(pg, "pause"); pg.click("#btnMenu"); wait_state(pg, "menu")
    check(pg.locator("#btnContinue").is_visible() and "nível 1" in pg.inner_text("#btnContinue").lower(), "Menu mostra 'Continuar · Nível 1'")
    pg.reload(); wait_state(pg, "menu"); check(pg.locator("#btnContinue").is_visible(), "progresso sobrevive ao recarregar a página")
    pg.click("#btnContinue"); wait_state(pg, "play")
    check(world(pg,"w.score")==777 and world(pg,"w.hp")==3, f"continua com pontos/vidas salvos ({world(pg,'w.score')}, {world(pg,'w.hp')})")
    pg.keyboard.press("Escape"); wait_state(pg, "pause"); pg.click("#btnMenu"); wait_state(pg, "menu")
    pg.click("#btnNew"); check("apagar" in pg.inner_text("#btnNew").lower() and pg.evaluate("Aguia.app.state")=="menu", "Novo jogo com progresso pede confirmação")
    pg.click("#btnNew"); wait_state(pg, "play"); check(True, "segundo clique inicia um jogo novo")
    check(world(pg,"w.score")==0, "jogo novo começa do zero")
    ctx.close()

    print("# Toque no celular (iPhone)")
    ctx = b.new_context(viewport={"width":390,"height":844}, device_scale_factor=3, is_mobile=True, has_touch=True); pg = ctx.new_page()
    pg.on("pageerror", lambda e: errs.append("pageerror "+str(e)))
    pg.goto(URL); wait_state(pg, "menu"); pg.wait_for_timeout(500)
    info = pg.evaluate("({H:Aguia.app.H, st:document.getElementById('stage').getBoundingClientRect().toJSON(), fill:document.getElementById('stage').classList.contains('fill')})")
    check(info["fill"] and abs(info["st"]["width"]-390)<1.5 and abs(info["st"]["height"]-844)<1.5, f"palco preenche a tela 390x844 (H lógico {info['H']})")
    pg.tap("#btnNew"); wait_state(pg, "play"); pg.wait_for_timeout(1300); pg.screenshot(path="/home/claude/s_m_play.png")
    cdp = ctx.new_cdp_session(pg); xa = world(pg, "w.px")
    def touch(t, x, y): cdp.send("Input.dispatchTouchEvent", {"type": t, "touchPoints": [] if t=="touchEnd" else [{"x": x, "y": y}]})
    touch("touchStart", 195, 700)
    for i in range(1, 13): touch("touchMove", 195 - i*8, 700); pg.wait_for_timeout(20)
    pg.wait_for_timeout(400); xb = world(pg, "w.px"); touch("touchEnd", 0, 0)
    check(xb < xa - 50, f"arrastar com o dedo move a águia ({xa:.0f} -> {xb:.0f})")
    pg.tap("#btnPause"); wait_state(pg, "pause"); check(True, "botão de pausa funciona no toque")
    pg.tap("#btnResume"); wait_state(pg, "play")
    pg.set_viewport_size({"width":844,"height":390}); pg.wait_for_timeout(400)
    check(pg.locator("#rotate").is_visible() and pg.evaluate("Aguia.app.state")=="pause", "celular deitado: aviso para girar e jogo pausa")
    pg.screenshot(path="/home/claude/s_m_land.png")
    pg.set_viewport_size({"width":390,"height":844}); pg.wait_for_timeout(400)
    check(pg.locator("#rotate").is_hidden(), "voltando para em pé, o aviso some")
    ctx.close(); b.close()
print("\nerros de console/página:", errs)
print("RESULTADO:", "tudo certo" if not fails and not errs else f"{len(fails)} falhas")
_srv.__exit__(None, None, None); sys.exit(1 if fails else 0)

_srv.__exit__(None, None, None)
